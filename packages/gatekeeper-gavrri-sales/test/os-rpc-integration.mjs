// Explicitly run against an isolated local OS with a fresh seeded D1.
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { connect, signUp, listConnectedAccounts, waitFor, stubFor, ObserverConfigRecorder } from '../../integration-tests/src/rpc-client.ts';
if(process.env.SALES_DISPOSABLE_DB!=='confirmed')throw new Error('Requires isolated disposable OS and D1');
const base=new URL(process.env.SALES_TEST_OS_URL || 'http://127.0.0.1:8789');
if(base.protocol!=='http:'||base.hostname!=='127.0.0.1'||!base.port||base.port==='8787'||base.pathname!=='/'||base.search||base.hash)throw new Error('Requires an isolated loopback OS, not port 8787');
const api=connect(base);
const suffix=randomBytes(5).toString('hex');
try {
  const alice=await signUp(api,`salestest${suffix}`);
  await alice.provisionAmbientAccount('gavrri_sales');
  const account=await waitFor('sales account',async()=>(await listConnectedAccounts(alice)).find(a=>a.vendorId==='gavrri_sales')??null);
  const workspace=await alice.newGadget();
  const gatekeeper=await workspace.newGatekeeper(account.id,'sales://local-demo');
  const session=await gatekeeper.openSession();
  const candidates=await session.listCandidates();
  assert.ok(candidates.items.length);
  const id=candidates.items[0].id;
  const before=(await session.listEvents(id)).items;
  await assert.rejects(async()=>await session.listCandidates("invalid-cursor"));
  await assert.rejects(async()=>await session.listEvents(id,"invalid-cursor"));
  await assert.rejects(async()=>await session.getMetrics({dataset:'actual',offer:null,currency:'JPY',month:'2026-10',asOf:'2026-10-28'}));
  const otherScope={companyId:'synthetic',offer:'Weibeo',dataset:'actual',currency:'JPY',amount:'10',kind:'revenue',occurredOn:'2026-10-28',periodStart:'2026-10-01',periodEnd:'2026-10-31',evidence:{sourceUrl:'https://example.com/',sourceRef:'other-scope',recordedOn:'2026-10-28',confirmation:'confirmed'}};
  await assert.rejects(async()=>await session.proposeAmount(otherScope,`scope-${suffix}`));
  assert.equal((await workspace.listActions({filter:'pending'})).entries.length,0);
  const request=`rpc-test-${suffix}`;
  const input={kind:'note',occurredOn:'2026-10-28',note:'架空のローカル統合テスト',evidence:{sourceUrl:'https://example.com/',sourceRef:request,recordedOn:'2026-10-28',confirmation:'confirmed'}};
  const proposal=await session.recordEvent(id,input,request);
  assert.equal(proposal.status,'pending');
  const duplicate=await session.recordEvent(id,input,request);
  assert.equal(duplicate.actionId,proposal.actionId);
  const pending=await waitFor('approval queue',async()=>{const page=await workspace.listActions({filter:'pending'});return page.entries.length?page.entries:null});
  assert.equal(pending.length,1);
  await workspace.approveAction(pending[0].id);
  await waitFor('saved event',async()=>{const entries=(await session.listEvents(id)).items;return entries.length===before.length+1?entries:null});
  async function approve(propose) {
    const result=await propose();
    assert.equal(result.status,'pending');
    const actions=await waitFor('proposed action',async()=>{const page=await workspace.listActions({filter:'pending'});return page.entries.length?page.entries:null});
    assert.equal(actions.length,1);
    await workspace.approveAction(actions[0].id);
  }
  const companyName=`架空会社 ${suffix}`;
  await approve(()=>session.proposeCompany(companyName,`company-${suffix}`));
  const company=(await session.listCompanies()).items.find(c=>c.name===companyName);
  assert.ok(company);
  await approve(()=>session.proposeCandidate(company.id,'DemoOffer','partner',`DEMO-${suffix}`,`candidate-${suffix}`));
  const candidate=(await session.listCandidates()).items.find(c=>c.companyName===companyName&&c.offer==='DemoOffer');
  assert.ok(candidate);
  assert.equal(candidate.contactAllowed,'unknown');
  const ev={sourceUrl:'https://example.com/',sourceRef:`permission-${suffix}`,recordedOn:'2026-10-28',confirmation:'confirmed'};
  await approve(()=>session.proposePermission(candidate.id,'yes',ev,candidate.version,`permission-${suffix}`));
  assert.equal((await session.listCandidates()).items.find(c=>c.id===candidate.id).contactAllowed,'yes');
  const common={companyId:company.id,offer:'DemoOffer',dataset:'demo',currency:'JPY',amount:'12000',evidence:ev};
  await approve(()=>session.proposeContract({...common,cadence:'annual',paidFrom:'2026-10-01',paidUntil:null,pauseFrom:null,pauseUntil:null,supersedes:null,evidence:{...ev,sourceRef:`contract-${suffix}`}},`contract-${suffix}`));
  await approve(()=>session.proposeAmount({...common,kind:'revenue',occurredOn:'2026-10-28',periodStart:'2026-10-01',periodEnd:'2026-10-31',evidence:{...ev,sourceRef:`amount-${suffix}`}},`amount-${suffix}`));
  const metric=await session.getMetrics({dataset:'demo',offer:'DemoOffer',currency:'JPY',month:'2026-10',asOf:'2026-10-28'});
  assert.equal(metric.revenue,'12000.00');
  assert.equal(metric.mrr,'1000.00');
  assert.ok((await session.listLimits()).items.length);
  assert.equal((await session.previewDemoRegistry()).total,1);
  const updated=(await session.listCandidates()).items.find(c=>c.id===candidate.id);
  await approve(()=>session.proposeNextAction(candidate.id,'架空の次対応','2026-11-01',updated.version,`next-${suffix}`));
  const afterNext=(await session.listCandidates()).items.find(c=>c.id===candidate.id);
  assert.equal(afterNext.nextAction,'架空の次対応');
  assert.equal(afterNext.nextActionDate,'2026-11-01');
  assert.equal(afterNext.version,updated.version+1);
  const aliasName=`架空別名 ${suffix}`;
  await approve(()=>session.proposeCompany(aliasName,`alias-company-${suffix}`));
  const companies=(await session.listCompanies()).items;
  const alias=companies.find(c=>c.name===aliasName);
  const target=companies.find(c=>c.id===company.id);
  assert.ok(alias&&target);
  await approve(()=>session.proposeLinkAlias(alias.id,target.id,target.version,`link-${suffix}`));
  const linked=(await session.listCompanies()).items;
  assert.equal(linked.find(c=>c.id===alias.id).canonicalId,target.id);
  assert.equal(linked.find(c=>c.id===target.id).version,target.version+1);
  const bob=await signUp(api,`salesother${suffix}`);
  await assert.rejects(async()=>await bob.provisionAmbientAccount('gavrri_sales'));
  await workspace.addCollaborator(`salesother${suffix}`,'build');
  const recorder=stubFor(new ObserverConfigRecorder());
  try{await assert.rejects(async()=>await bob.openGadget((await workspace.getMetadata()).id,undefined,recorder));}finally{recorder[Symbol.dispose]()}
  console.log('PASS: real OS demo read, actual scope reads and writes denied, duplicate approval prevented, approval applied and reread, company/candidate/permission/contract/amount/next action/alias persisted, other observer denied');
}finally{api[Symbol.dispose]()}
